-- Example trigger: record direct changes to the loan table
CREATE OR REPLACE TRIGGER TRG_LIB_LOAN_AUDIT
AFTER INSERT OR UPDATE OF RETURN_DATE ON LIB_LOANS
FOR EACH ROW
BEGIN
  IF INSERTING THEN
    INSERT INTO LIB_AUDIT(ACTION_NAME, DETAILS)
      VALUES('LOAN_CREATED', 'Loan='||:NEW.LOAN_ID);
  ELSIF UPDATING THEN
    INSERT INTO LIB_AUDIT(ACTION_NAME, DETAILS)
      VALUES('LOAN_UPDATED', 'Loan='||:NEW.LOAN_ID||
        '; Return date='||TO_CHAR(:NEW.RETURN_DATE,'YYYY-MM-DD'));
  END IF;
END;
/
