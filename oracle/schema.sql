-- Oracle schema for the PL/SQL component (run in SQL*Plus or SQL Developer)
CREATE TABLE LIB_BOOKS (
  BOOK_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TITLE VARCHAR2(150) NOT NULL,
  AUTHOR VARCHAR2(100) NOT NULL,
  CATEGORY VARCHAR2(60),
  ISBN VARCHAR2(20) UNIQUE,
  TOTAL_COPIES NUMBER DEFAULT 1 NOT NULL,
  AVAILABLE_COPIES NUMBER DEFAULT 1 NOT NULL,
  CONSTRAINT CK_BOOK_COPIES CHECK (AVAILABLE_COPIES BETWEEN 0 AND TOTAL_COPIES)
);
CREATE TABLE LIB_MEMBERS (
  MEMBER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  FULL_NAME VARCHAR2(100) NOT NULL,
  EMAIL VARCHAR2(150) UNIQUE NOT NULL,
  PHONE VARCHAR2(25)
);
CREATE TABLE LIB_LOANS (
  LOAN_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  BOOK_ID NUMBER NOT NULL REFERENCES LIB_BOOKS(BOOK_ID),
  MEMBER_ID NUMBER NOT NULL REFERENCES LIB_MEMBERS(MEMBER_ID),
  ISSUE_DATE DATE DEFAULT SYSDATE NOT NULL,
  DUE_DATE DATE NOT NULL,
  RETURN_DATE DATE,
  FINE_AMOUNT NUMBER(10,2) DEFAULT 0 NOT NULL
);
CREATE TABLE LIB_AUDIT (
  AUDIT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ACTION_NAME VARCHAR2(30) NOT NULL,
  DETAILS VARCHAR2(300),
  ACTION_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
