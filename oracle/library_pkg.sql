-- Core PL/SQL package: fine function, issue/return procedures, overdue cursor
CREATE OR REPLACE PACKAGE LIBRARY_PKG AS
  FUNCTION CALCULATE_FINE(P_DUE_DATE DATE, P_RETURN_DATE DATE DEFAULT SYSDATE)
    RETURN NUMBER;
  PROCEDURE ISSUE_BOOK(P_BOOK_ID NUMBER, P_MEMBER_ID NUMBER);
  PROCEDURE RETURN_BOOK(P_LOAN_ID NUMBER);
  PROCEDURE LIST_OVERDUE;
END LIBRARY_PKG;
/
CREATE OR REPLACE PACKAGE BODY LIBRARY_PKG AS
  FUNCTION CALCULATE_FINE(P_DUE_DATE DATE, P_RETURN_DATE DATE DEFAULT SYSDATE)
    RETURN NUMBER IS
    V_DAYS_LATE NUMBER;
  BEGIN
    V_DAYS_LATE := GREATEST(TRUNC(P_RETURN_DATE) - TRUNC(P_DUE_DATE), 0);
    RETURN V_DAYS_LATE * 5;
  END;

  PROCEDURE ISSUE_BOOK(P_BOOK_ID NUMBER, P_MEMBER_ID NUMBER) IS
    V_AVAILABLE NUMBER;
  BEGIN
    SELECT AVAILABLE_COPIES INTO V_AVAILABLE
      FROM LIB_BOOKS WHERE BOOK_ID = P_BOOK_ID FOR UPDATE;
    IF V_AVAILABLE < 1 THEN
      RAISE_APPLICATION_ERROR(-20001, 'No available copies.');
    END IF;
    INSERT INTO LIB_LOANS(BOOK_ID, MEMBER_ID, ISSUE_DATE, DUE_DATE)
      VALUES(P_BOOK_ID, P_MEMBER_ID, TRUNC(SYSDATE), TRUNC(SYSDATE)+14);
    UPDATE LIB_BOOKS SET AVAILABLE_COPIES = AVAILABLE_COPIES - 1
      WHERE BOOK_ID = P_BOOK_ID;
    INSERT INTO LIB_AUDIT(ACTION_NAME, DETAILS)
      VALUES('ISSUE_BOOK', 'Book='||P_BOOK_ID||'; Member='||P_MEMBER_ID);
    COMMIT;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      RAISE_APPLICATION_ERROR(-20002, 'Book not found.');
    WHEN OTHERS THEN
      ROLLBACK;
      RAISE;
  END;

  PROCEDURE RETURN_BOOK(P_LOAN_ID NUMBER) IS
    V_BOOK_ID NUMBER;
    V_DUE_DATE DATE;
    V_RETURN_DATE DATE := TRUNC(SYSDATE);
    V_FINE NUMBER;
  BEGIN
    SELECT BOOK_ID, DUE_DATE INTO V_BOOK_ID, V_DUE_DATE
      FROM LIB_LOANS WHERE LOAN_ID=P_LOAN_ID AND RETURN_DATE IS NULL
      FOR UPDATE;
    V_FINE := CALCULATE_FINE(V_DUE_DATE, V_RETURN_DATE);
    UPDATE LIB_LOANS SET RETURN_DATE=V_RETURN_DATE, FINE_AMOUNT=V_FINE
      WHERE LOAN_ID=P_LOAN_ID;
    UPDATE LIB_BOOKS SET AVAILABLE_COPIES=AVAILABLE_COPIES+1
      WHERE BOOK_ID=V_BOOK_ID;
    INSERT INTO LIB_AUDIT(ACTION_NAME, DETAILS)
      VALUES('RETURN_BOOK', 'Loan='||P_LOAN_ID||'; Fine='||V_FINE);
    COMMIT;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      RAISE_APPLICATION_ERROR(-20003, 'Active loan not found.');
    WHEN OTHERS THEN
      ROLLBACK;
      RAISE;
  END;

  PROCEDURE LIST_OVERDUE IS
    CURSOR C_OVERDUE IS
      SELECT L.LOAN_ID, B.TITLE, M.FULL_NAME, L.DUE_DATE,
             TRUNC(SYSDATE)-TRUNC(L.DUE_DATE) DAYS_LATE
      FROM LIB_LOANS L
      JOIN LIB_BOOKS B ON B.BOOK_ID=L.BOOK_ID
      JOIN LIB_MEMBERS M ON M.MEMBER_ID=L.MEMBER_ID
      WHERE L.RETURN_DATE IS NULL AND L.DUE_DATE < TRUNC(SYSDATE)
      ORDER BY L.DUE_DATE;
    V_ROW C_OVERDUE%ROWTYPE;
  BEGIN
    OPEN C_OVERDUE;
    LOOP
      FETCH C_OVERDUE INTO V_ROW;
      EXIT WHEN C_OVERDUE%NOTFOUND;
      DBMS_OUTPUT.PUT_LINE(V_ROW.LOAN_ID||' | '||V_ROW.TITLE||' | '||
        V_ROW.FULL_NAME||' | days late: '||V_ROW.DAYS_LATE);
    END LOOP;
    CLOSE C_OVERDUE;
  END;
END LIBRARY_PKG;
